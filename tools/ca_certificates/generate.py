"""Generate immutable embedded PEM data only from a verified snapshot."""
import json
from pathlib import Path
import sys

from bundle import checked


def main() -> None:
    pem, manifest, output = map(Path, sys.argv[1:])
    pin, records = checked(pem, manifest)
    content = b''.join(item[1] for item in records).decode('ascii')
    lines = ''.join(json.dumps(line) + '\n' for line in content.splitlines(keepends=True))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        '// Generated by tools/ca_certificates/generate.py. Do not edit.\n'
        '// Certificate data: Mozilla/curl, MPL-2.0; see third_party/ca_certificates.\n'
        '#ifndef WEBCPP_DETAIL_CA_CERTIFICATES_HPP\n'
        '#define WEBCPP_DETAIL_CA_CERTIFICATES_HPP\n'
        '#include <cstddef>\n'
        'namespace webcpp::detail::ca_certificates {\n'
        'inline constexpr char pem[] =\n' + lines + ';\n'
        f'inline constexpr char date[] = {json.dumps(pin["date"])};\n'
        f'inline constexpr char sha256[] = {json.dumps(pin["sha256"])};\n'
        f'inline constexpr std::size_t count = {len(records)};\n'
        '}\n#endif\n')


if __name__ == '__main__':
    main()
